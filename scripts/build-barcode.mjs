import { build } from 'esbuild';
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';

await mkdir('public/vendor', { recursive: true });
const result = await build({
  entryPoints: ['src/barcode-decoder.js'], outfile: 'public/vendor/barcode-decoder.js', bundle: true,
  format: 'esm', platform: 'browser', target: ['safari15', 'chrome90'], minify: true,
  legalComments: 'eof', metafile: true,
  banner: { js: '/*! ZXing EAN-13 decoder. Apache-2.0; see ZXING-LICENSE.txt and ZXING-NOTICE.txt. Generated by npm run build:barcode. */' },
});
await copyFile('node_modules/@zxing/library/LICENSE', 'public/vendor/ZXING-LICENSE.txt');
const notices = new Set();
for (const name of Object.keys(result.metafile.inputs).filter(name => name.includes('@zxing/library/'))) {
  const source = await readFile(name, 'utf8');
  for (const match of source.matchAll(/Copyright[^\n\r]*/g)) notices.add(match[0].replace(/\*\/$/, '').trim());
}
await writeFile('public/vendor/ZXING-NOTICE.txt', 'ZXing TypeScript library — https://github.com/zxing-js/library\nApache License 2.0\n\n' + [...notices].sort().join('\n') + '\n');
console.log('Built local EAN-13 decoder and license notices.');
